import { useState } from 'react';
import { useToastStore } from '../store';

const EWB_STATUSES = ['in_transit', 'delivered', 'cancelled'];
const BLANK = { inv_no: '', gen_date: new Date().toISOString().slice(0, 10), vehicle: '', from: 'Krishnagiri (635203)', to: '', distance_km: '', valid_till: '', value: '', status: 'in_transit' };

const printEWB = (e: any) => {
  const w = window.open('', '_blank', 'width=800,height=600');
  if (!w) return;
  w.document.write(`
    <html><head><title>E-Way Bill — ${e.ewb_no}</title><style>
      body { font-family: 'Courier New', monospace; font-size: 11px; color: #000; margin: 20px; }
      .hdr { text-align: center; border-bottom: 2px solid #000; padding-bottom: 8px; margin-bottom: 12px; }
      .hdr h2 { margin: 0; font-size: 16px; }
      .hdr p { margin: 2px 0; font-size: 10px; }
      .grid { display: grid; grid-template-columns: 1fr 1fr; gap: 8px; margin-bottom: 12px; }
      .field { border: 1px solid #ccc; padding: 6px 8px; }
      .label { font-size: 8px; text-transform: uppercase; letter-spacing: 1px; color: #666; }
      .val { font-size: 12px; font-weight: bold; margin-top: 2px; }
      .ewb-no { font-size: 20px; font-weight: bold; border: 2px solid #000; padding: 8px 16px; text-align: center; margin: 12px 0; }
      .footer { margin-top: 20px; font-size: 9px; color: #666; border-top: 1px solid #ccc; padding-top: 8px; }
      @media print { body { margin: 0; } }
    </style></head><body>
      <div class="hdr">
        <h2>E-WAY BILL</h2>
        <p>Rule 138 CGST Rules, 2017 — HSN 2516 — Granite Blocks</p>
      </div>
      <div class="ewb-no">${e.ewb_no}</div>
      <div class="grid">
        <div class="field"><div class="label">Invoice No.</div><div class="val">${e.inv_no}</div></div>
        <div class="field"><div class="label">Generated Date</div><div class="val">${e.gen_date}</div></div>
        <div class="field"><div class="label">Valid Till</div><div class="val">${e.valid_till}</div></div>
        <div class="field"><div class="label">Vehicle No.</div><div class="val">${e.vehicle}</div></div>
        <div class="field"><div class="label">From</div><div class="val">${e.from}</div></div>
        <div class="field"><div class="label">To</div><div class="val">${e.to}</div></div>
        <div class="field"><div class="label">Distance</div><div class="val">${e.distance_km} km</div></div>
        <div class="field"><div class="label">Invoice Value</div><div class="val">₹${Number(e.value).toLocaleString()}</div></div>
      </div>
      <div class="footer">
        Generated by Vatsin Granite ERP · GSTIN: 33ABGXX1234X1ZX · HSN 2516 (5% GST) · Validity: 1 day per 200 km
      </div>
      <script>window.print(); window.close();<\/script>
    </body></html>
  `);
  w.document.close();
};

export default function EWayBillPage() {
  const { notify } = useToastStore();
  const [showModal, setShowModal] = useState(false);
  const [editId, setEditId] = useState<number | null>(null);
  const [form, setForm] = useState<any>(BLANK);

  const [ewbs, setEwbs] = useState<any[]>([]);

  const nextId = () => (ewbs.length === 0 ? 1 : Math.max(...ewbs.map(e => e.id)) + 1);
  const nextEWBNo = () => `EWB-41000${1234 + nextId()}`;
  const calcValidity = (date: string, dist: number) => {
    if (!date || !dist) return '';
    const d = new Date(date);
    d.setDate(d.getDate() + Math.max(1, Math.ceil(dist / 200)));
    return d.toISOString().slice(0, 10);
  };

  const openAdd = () => { setForm(BLANK); setEditId(null); setShowModal(true); };
  const openEdit = (e: any) => { setForm({ ...e, distance_km: String(e.distance_km), value: String(e.value) }); setEditId(e.id); setShowModal(true); };

  const handleSave = () => {
    if (!form.inv_no || !form.vehicle) { notify('Invoice No. and vehicle are required', 'error'); return; }
    const dist = Number(form.distance_km) || 0;
    const valid_till = form.valid_till || calcValidity(form.gen_date, dist);
    const rec = { ...form, distance_km: dist, value: Number(form.value) || 0, valid_till };
    if (editId !== null) {
      setEwbs(prev => prev.map(e => e.id === editId ? { ...e, ...rec } : e));
      notify('EWB updated');
    } else {
      setEwbs(prev => [{ ...rec, id: nextId(), ewb_no: nextEWBNo() }, ...prev]);
      notify('E-Way Bill generated');
    }
    setShowModal(false);
  };

  const handleDelete = (id: number) => { setEwbs(prev => prev.filter(e => e.id !== id)); notify('EWB deleted'); };
  const f = (k: string) => (e: any) => setForm((p: any) => ({ ...p, [k]: e.target.value }));

  return (
    <div className="page">
      <div className="page-header">
        <div>
          <div className="ph-title">E-Way Bill</div>
          <div className="ph-sub">M10 — NIC EWB Portal · Rule 138 CGST · Part-A / Part-B · Validity tracking</div>
        </div>
        <div style={{ display: 'flex', gap: 8 }}>
          <button className="btn btn-s" onClick={() => notify('Consolidated EWB for multiple invoices', 'warn')}>Consolidated EWB</button>
          <button className="btn btn-p" onClick={openAdd}>+ Generate EWB</button>
        </div>
      </div>

      <div className="sc-grid">
        <div className="sc s"><div className="sc-lbl">Active EWBs</div><div className="sc-val">{ewbs.filter(e => e.status === 'in_transit').length}</div><div className="sc-sub">In transit</div></div>
        <div className="sc r"><div className="sc-lbl">Delivered</div><div className="sc-val">{ewbs.filter(e => e.status === 'delivered').length}</div><div className="sc-sub">Completed</div></div>
        <div className="sc g"><div className="sc-lbl">May Generated</div><div className="sc-val">{ewbs.length}</div><div className="sc-sub">Total this month</div></div>
        <div className="sc a"><div className="sc-lbl">Expiring Soon</div><div className="sc-val">0</div><div className="sc-sub">Next 24 hrs</div></div>
      </div>

      <div className="card">
        <div className="card-head"><div className="card-title">E-Way Bill Register — {ewbs.length} records</div></div>
        <div className="tw">
          <table className="dt">
            <thead>
              <tr><th>EWB No.</th><th>Invoice</th><th>Gen Date</th><th>Vehicle</th><th>From</th><th>To</th><th className="r">Distance</th><th>Valid Till</th><th className="r">Value (₹)</th><th>Status</th><th>Actions</th></tr>
            </thead>
            <tbody>
              {ewbs.map(e => (
                <tr key={e.id}>
                  <td className="tdm tdc">{e.ewb_no}</td>
                  <td className="tdm">{e.inv_no}</td>
                  <td className="tdm">{e.gen_date}</td>
                  <td className="tdm">{e.vehicle}</td>
                  <td>{e.from}</td>
                  <td>{e.to}</td>
                  <td className="tda">{e.distance_km} km</td>
                  <td className="tdm">{e.valid_till}</td>
                  <td className="tda">₹{Number(e.value).toLocaleString()}</td>
                  <td><span className={`bdg ${e.status === 'delivered' ? 'b-s' : e.status === 'in_transit' ? 'b-b' : 'b-d'}`}>{e.status}</span></td>
                  <td>
                    <div style={{ display: 'flex', gap: 4 }}>
                      <button className="btn btn-xs btn-s" onClick={() => openEdit(e)}>Edit</button>
                      <button className="btn btn-xs btn-s" onClick={() => printEWB(e)}>Print</button>
                      <button className="btn btn-xs btn-s" style={{ color: 'var(--red)' }} onClick={() => handleDelete(e.id)}>Del</button>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      <div className="card">
        <div className="card-head"><div className="card-title">EWB Rules — Quick Reference</div></div>
        <div className="card-body">
          <div className="fg3">
            {[
              ['Threshold', '₹50,000 and above (B2B). Intra-TN as notified.'],
              ['Validity', '1 day per 200 km (regular road); multimodal as per CGST rules'],
              ['HSN 2516 Rate', '5% GST (crude/roughly trimmed granite blocks)'],
              ['Part-A', 'Invoice details — generated by supplier before despatch'],
              ['Part-B', 'Vehicle details — updated by transporter / supplier'],
              ['Cancellation', 'Within 24 hours if not in transit'],
            ].map(([k, v]) => (
              <div key={k as string} style={{ marginBottom: 8 }}>
                <div style={{ fontFamily: 'IBM Plex Mono, monospace', fontSize: 7.5, letterSpacing: 1.5, textTransform: 'uppercase', color: 'var(--rust)', marginBottom: 3 }}>{k}</div>
                <div style={{ fontSize: 11, color: 'var(--t2)' }}>{v}</div>
              </div>
            ))}
          </div>
        </div>
      </div>

      {showModal && (
        <div className="modal-backdrop" onClick={() => setShowModal(false)}>
          <div className="modal" onClick={e => e.stopPropagation()} style={{ maxWidth: 520 }}>
            <div className="modal-head">
              <div className="modal-title">{editId !== null ? 'Edit E-Way Bill' : 'Generate E-Way Bill'}</div>
              <button className="modal-close" onClick={() => setShowModal(false)}>✕</button>
            </div>
            <div className="modal-body">
              <div className="fg2">
                <div className="fg"><label className="fl">Invoice No. *</label><input className="fi" value={form.inv_no} onChange={f('inv_no')} placeholder="ABG/INV/2526/004" /></div>
                <div className="fg"><label className="fl">Generation Date</label><input className="fi" type="date" value={form.gen_date} onChange={f('gen_date')} /></div>
              </div>
              <div className="fg2">
                <div className="fg"><label className="fl">Vehicle No. *</label><input className="fi" value={form.vehicle} onChange={f('vehicle')} placeholder="TN-33-AB-1234" /></div>
                <div className="fg"><label className="fl">Invoice Value (₹)</label><input className="fi" type="number" value={form.value} onChange={f('value')} placeholder="0" /></div>
              </div>
              <div className="fg2">
                <div className="fg"><label className="fl">From (Place + PIN)</label><input className="fi" value={form.from} onChange={f('from')} placeholder="Krishnagiri (635203)" /></div>
                <div className="fg"><label className="fl">To (Place + PIN)</label><input className="fi" value={form.to} onChange={f('to')} placeholder="Chennai (600028)" /></div>
              </div>
              <div className="fg3">
                <div className="fg"><label className="fl">Distance (km)</label><input className="fi" type="number" value={form.distance_km} onChange={f('distance_km')} placeholder="310" /></div>
                <div className="fg"><label className="fl">Valid Till (auto)</label><input className="fi" type="date" value={form.valid_till || calcValidity(form.gen_date, Number(form.distance_km))} onChange={f('valid_till')} /></div>
                <div className="fg"><label className="fl">Status</label><select className="fsel" value={form.status} onChange={f('status')}>{EWB_STATUSES.map(s => <option key={s}>{s}</option>)}</select></div>
              </div>
            </div>
            <div className="modal-foot">
              <button className="btn btn-s" onClick={() => setShowModal(false)}>Cancel</button>
              <button className="btn btn-p" onClick={handleSave}>{editId !== null ? 'Update EWB' : 'Generate EWB'}</button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
